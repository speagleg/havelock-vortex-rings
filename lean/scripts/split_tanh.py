"""Split the generated TanhAlgebra.lean into Havelock/Tanh/*.lean modules.

Usage: python lean/scripts/split_tanh.py GENERATED.lean lean

GENERATED.lean is the single file written by tanh/lean_gen/gen.py (the pre-split TanhAlgebra.lean). This
script replaces lean/Havelock/Tanh/*.lean and rewrites lean/Havelock/TanhAlgebra.lean as a thin module that imports
them and keeps the header comment and the #print axioms footer. Statements and proofs are copied verbatim.
"""
import glob
import os
import re
import sys

src, leandir = sys.argv[1], sys.argv[2]
L = open(src, encoding='utf-8').read().split('\n')


def find(pred, start=0):
    for i in range(start, len(L)):
        if pred(L[i]):
            return i
    raise SystemExit('marker not found')


i_import = find(lambda l: l == 'import Mathlib')
i_ns = find(lambda l: l == 'namespace Havelock.Tanh')
i_cert = find(lambda l: l.startswith('/-! ### N = 2 -/'))
i_extra = find(lambda l: l.startswith('/-! ### Factorisations'))
i_end = find(lambda l: l == 'end Havelock.Tanh')
heads = [i for i in range(i_cert, i_extra) if L[i].startswith('/-! ### N = ')]
Ns = [int(re.match(r'/-! ### N = (\d+)', L[i]).group(1)) for i in heads]
bounds = heads + [i_extra]

header_doc = '\n'.join(L[:i_import]).rstrip('\n')
footer = '\n'.join(L[i_end + 1:]).strip('\n')
general_body = '\n'.join(L[i_ns + 1:i_cert]).strip('\n')
sections = {N: '\n'.join(L[bounds[k]:bounds[k + 1]]).strip('\n') for k, N in enumerate(Ns)}
extras_body = '\n'.join(L[i_extra:i_end]).strip('\n')

GENERAL_IMPORTS = [  # `#min_imports` of General, plus the tactics used by the certificate modules
    'Mathlib.Algebra.Order.Star.Real', 'Mathlib.Algebra.Ring.IsFormallyReal',
    'Mathlib.Analysis.Calculus.Deriv.MeanValue', 'Mathlib.Analysis.InnerProductSpace.Basic',
    'Mathlib.Analysis.LocallyConvex.AbsConvexOpen', 'Mathlib.LinearAlgebra.Matrix.Determinant.Basic',
    'Mathlib.Topology.Algebra.Module.ModuleTopology',
    'Mathlib.Tactic.FieldSimp', 'Mathlib.Tactic.IntervalCases', 'Mathlib.Tactic.Linarith',
    'Mathlib.Tactic.NormNum', 'Mathlib.Tactic.Positivity', 'Mathlib.Tactic.Ring']
EXTRAS_IMPORTS = ['Mathlib.Tactic.ComputeDegree', 'Mathlib.RingTheory.IntegralClosure.IsIntegral.Basic',
                  'Mathlib.Analysis.SpecialFunctions.Trigonometric.DerivHyp']
PART_BYTES = 40000  # split a certificate section into ceil(size / PART_BYTES) modules


def split_parts(text, k):
    """Split at top-level declaration boundaries (blank line followed by a column-0 line) into k
    pieces of about equal size."""
    lines = text.split('\n')
    cuts = [i for i in range(1, len(lines)) if lines[i - 1] == '' and lines[i][:1] not in ('', ' ')]
    chosen = []
    for j in range(1, k):
        target = len(text) * j / k
        chosen.append(min(cuts, key=lambda i: abs(len('\n'.join(lines[:i])) - target)))
    b = [0] + chosen + [len(lines)]
    return ['\n'.join(lines[b[t]:b[t + 1]]).strip('\n') for t in range(k)]


PRE = 'set_option linter.unusedSimpArgs false\n\nnoncomputable section\n\nnamespace Havelock.Tanh\n\n'
POST = '\n\nend Havelock.Tanh\n'


def module(imports, doc, body):
    return '\n'.join(f'import {m}' for m in imports) + '\n\n' + doc.strip() + '\n\n' + PRE + body + POST


outdir = os.path.join(leandir, 'Havelock', 'Tanh')
os.makedirs(outdir, exist_ok=True)
files = {}
files['General'] = module(
    GENERAL_IMPORTS,
    '/-! # Tanh model: definitions and all-`N` lemmas\n\n'
    'Split from the generator output of `tanh/lean_gen/gen.py` (the part that comes from\n'
    '`tanh/lean_gen/General.lean`). See `Havelock/TanhAlgebra.lean` for the overview. -/',
    general_body)
small = [N for N in Ns if N <= 7]
big = [N for N in Ns if N >= 8]
files['StableN2to7'] = module(
    ['Havelock.Tanh.General'],
    f'/-! # Tanh model: certificates for N = {small[0]}..{small[-1]} (note Thm 6(a))\n\n'
    'Generated by `tanh/lean_gen/gen.py` (`gen_small`). -/',
    '\n\n'.join(sections[N] for N in small))
last = {}
cert_mods = []
for N in big:
    k = -(-len(sections[N].encode('utf-8')) // PART_BYTES)
    parts = split_parts(sections[N], k) if k > 1 else [sections[N]]
    prev = 'Havelock.Tanh.General'
    for t, body in enumerate(parts):
        name = f'CertN{N}' + ('abcdefgh'[t] if k > 1 else '')
        what = f' (part {t + 1} of {k})' if k > 1 else ''
        files[name] = module(
            [prev],
            f'/-! # Tanh model: certificate for N = {N}{what} (note Thm 6(b))\n\n'
            'Generated by `tanh/lean_gen/gen.py` (`gen_big`). -/',
            body)
        prev = f'Havelock.Tanh.{name}'
        cert_mods.append(name)
    last[N] = prev
files['Extras'] = module(
    [last[N] for N in big] + EXTRAS_IMPORTS,
    '/-! # Tanh model: factorisations, palindromy, Krein window, ξ*(8) a unit, hyperbolic radius\n\n'
    'Generated by `tanh/lean_gen/gen.py` (`gen_extras` and `N8_EXTRA`). -/',
    extras_body)
for old in glob.glob(os.path.join(outdir, '*.lean')):
    os.remove(old)
for name, text in files.items():
    open(os.path.join(outdir, name + '.lean'), 'w', encoding='utf-8', newline='\n').write(text)

mods = ['General', 'StableN2to7'] + cert_mods + ['Extras']
thin = (header_doc + '\n' + '\n'.join(f'import Havelock.Tanh.{m}' for m in mods) + '\n\n'
        '/-! The content is split into the modules `Havelock.Tanh.*` imported above (to keep the peak\n'
        'memory of each module small); this module re-exports them and prints the axiom audit. -/\n\n'
        + footer + '\n')
open(os.path.join(leandir, 'Havelock', 'TanhAlgebra.lean'), 'w', encoding='utf-8', newline='\n').write(thin)
print('modules:', mods)
