"""Generate Lean irreducibility certificates (lean/Havelock/Tanh/IrredN<N>.lean) for f_N.

Usage: python3 lean_irred_gen.py N p   (p prime, p does not divide lead(f_N), f_N irreducible mod p).
Primes used: N=8..16 -> 7, 13, 107, 17, 11, 101, 3, 29, 163.
"""
import re, sys, math
import os
REPO=os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'lean', 'Havelock', 'Tanh') + os.sep
FILES={8:'CertN8',9:'CertN9',10:'CertN10',11:'CertN11',12:'CertN12b',13:'CertN13b',14:'CertN14b',15:'CertN15b',16:'CertN16c'}
def getf(N):
    s=open(REPO+FILES[N]+'.lean').read()
    m=re.search(r'def f%d : List ℤ := \[([^\]]*)\]'%N,s)
    return [int(x) for x in m.group(1).split(',')]
def norm(a,p):
    a=[x%p for x in a]
    while a and a[-1]==0: a.pop()
    return a
def mul(a,b,p):
    if not a or not b: return []
    r=[0]*(len(a)+len(b)-1)
    for i,x in enumerate(a):
        if x:
            for j,y in enumerate(b): r[i+j]+=x*y
    return norm(r,p)
def sub(a,b,p):
    n=max(len(a),len(b)); return norm([(a[i] if i<len(a) else 0)-(b[i] if i<len(b) else 0) for i in range(n)],p)
def divmod_(a,h,p):
    a=norm(a,p); h=norm(h,p); inv=pow(h[-1],-1,p); q=[0]*max(0,len(a)-len(h)+1)
    a=a[:]
    while len(a)>=len(h):
        c=a[-1]*inv%p; k=len(a)-len(h); q[k]=c
        for i,y in enumerate(h): a[k+i]=(a[k+i]-c*y)%p
        a=norm(a,p)
    return norm(q,p),a
def egcd(a,b,p):
    # returns g,u,v with u a + v b = g monic
    r0,r1=norm(a,p),norm(b,p); u0,u1=[1],[]; v0,v1=[],[1]
    while r1:
        q,r=divmod_(r0,r1,p)
        r0,r1=r1,r; u0,u1=u1,sub(u0,mul(q,u1,p),p); v0,v1=v1,sub(v0,mul(q,v1,p),p)
    inv=pow(r0[-1],-1,p)
    return mul(r0,[inv],p),mul(u0,[inv],p),mul(v0,[inv],p)
# Lean checker simulation
def padd(a,b):
    n=max(len(a),len(b)); return [(a[i] if i<len(a) else 0)+(b[i] if i<len(b) else 0) for i in range(n)]
def pmul(a,b):
    if not a: return []
    return padd([a[0]*x for x in b],[0]+pmul(a[1:],b))
def psub(a,b): return padd(a,[-x for x in b])
def allDvd(p,l): return all(x%p==0 for x in l)
def lincomb(ms,r):
    if not r or not ms: return []
    return padd([r[0]*x for x in ms[0]],lincomb(ms[1:],r[1:]))
def checkAll(p,h,c):
    q0,m1,tab,chain,i,j=c
    ok=allDvd(p,psub([0]*p+[1],padd(m1,pmul(q0,h))))
    cur=m1
    for nxt,q in tab:
        ok&=allDvd(p,psub(pmul(cur,m1),padd(nxt,pmul(q,h)))); cur=nxt
    ms=[[1],m1]+[t[0] for t in tab]
    cur=[0,1]
    for nxt,u,v in chain:
        ok&=len(cur)<=len(ms)
        ok&=allDvd(p,psub(lincomb(ms,cur),nxt))
        ok&=allDvd(p,psub(padd(pmul(u,h),pmul(v,psub(nxt,[0,1]))),[1]))
        cur=nxt
    ok&=len(h)>=2 and (len(h)-1)//2<=len(chain) and h[-1]%p!=0 and math.gcd(h[i],h[j])==1
    return ok
def cert(N,p):
    h=getf(N); n=len(h)-1; hb=norm(h,p); assert len(hb)==n+1
    xp=[0]*p+[1]
    q0,m1=divmod_(xp,hb,p)
    tab=[]; cur=m1
    for k in range(2,n):
        q,r=divmod_(mul(cur,m1,p),hb,p); tab.append((r,q)); cur=r
    ms=[[1],m1]+[t[0] for t in tab]
    chain=[]; cur=[0,1]
    for d in range(1,n//2+1):
        nxt=norm(lincomb(ms,cur),p)
        g,u,v=egcd(hb,sub(nxt,[0,1],p),p)
        if g!=[1]: return None
        chain.append((nxt,u,v)); cur=nxt
    i,j=next((i,j) for i in range(len(h)) for j in range(i+1,len(h)) if math.gcd(h[i],h[j])==1)
    c=(q0,m1,tab,chain,i,j)
    assert checkAll(p,h,c)
    return c
def L(l): return '['+', '.join(map(str,l))+']'
def lean(N,p,c):
    q0,m1,tab,chain,i,j=c
    tabs=',\n    '.join('(%s,\n      %s)'%(L(a),L(b)) for a,b in tab)
    chs=',\n    '.join('(%s,\n      %s,\n      %s)'%(L(a),L(b),L(cc)) for a,b,cc in chain)
    return f"""import Havelock.Tanh.IrredBasic
import Mathlib.Tactic.NormNum.Prime
import Havelock.Tanh.{FILES[N]}

/-! # Irreducibility of `f_{N}` (note §"Irreducibility")

`f_{N}` (degree {len(getf(N))-1}) is irreducible modulo `p = {p}` (which does not divide its leading coefficient), hence
irreducible over `ℤ` and `ℚ`. Certificate generated by `tanh/irreducibility/lean_irred_gen.py`; it is
checked by `decide +kernel` against `Havelock.Tanh.Irred.checkAll`. -/

namespace Havelock.Tanh.Irred

open Polynomial

/-- Certificate for `f_{N}` modulo `{p}`. -/
def certN{N} : Cert where
  q0 := {L(q0)}
  m1 := {L(m1)}
  tab := [
    {tabs}]
  chain := [
    {chs}]
  i := {i}
  j := {j}

theorem checkAll_f{N} : checkAll {p} f{N} certN{N} = true := by decide +kernel

/-- `f_{N}` is irreducible modulo `{p}` (note §"Irreducibility"). -/
theorem f{N}_irreducible_mod : Irreducible (toPoly f{N} : (ZMod {p})[X]) :=
  have : Fact (Nat.Prime {p}) := ⟨by norm_num⟩
  irreducible_zmod_of_checkAll {p} f{N} certN{N} checkAll_f{N}

/-- The threshold polynomial `f_{N}` is irreducible over `ℤ` and over `ℚ` (note §"Irreducibility"). -/
theorem f{N}_irreducible : Irreducible (toPoly f{N} : ℤ[X]) ∧ Irreducible (toPoly f{N} : ℚ[X]) :=
  irreducible_of_checkAll {p} (by norm_num) f{N} certN{N} checkAll_f{N}

end Havelock.Tanh.Irred
"""
if __name__=='__main__':
    N=int(sys.argv[1]); p=int(sys.argv[2])
    c=cert(N,p)
    if c is None: print('NOT irreducible mod',p); sys.exit(1)
    open(REPO+'IrredN%d.lean'%N,'w').write(lean(N,p,c))
    print('wrote',N,p, 'numbers:', sum(len(x) for x in [c[0],c[1]])+sum(len(a)+len(b) for a,b in c[2])+sum(len(a)+len(b)+len(cc) for a,b,cc in c[3]))
